"""Render Markdown tables from the stored analysis artifacts.

The narrative report is committed as a static document, but every table in it is
generated by this script from ``results/`` so the numbers cannot drift.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]
METRICS = ("accuracy", "macro_f1")


def load_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def markdown_table(rows: list[dict], columns: list[tuple[str, str]], float_digits: int = 4) -> str:
    """Render rows as a GitHub Markdown table with formatted floats."""
    header = "| " + " | ".join(label for _, label in columns) + " |"
    separator = "|" + "|".join(["---"] * len(columns)) + "|"
    lines = [header, separator]
    for row in rows:
        cells = []
        for key, _ in columns:
            value = row.get(key)
            if value is None:
                cells.append("—")
            elif isinstance(value, float):
                cells.append(f"{value:.{float_digits}f}")
            elif isinstance(value, bool):
                cells.append("yes" if value else "no")
            else:
                cells.append(str(value))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def write(path: Path, title: str, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"# {title}\n\n{body}\n", encoding="utf-8")
    print(f"table: {path}", flush=True)


def mean_std(rows: list[dict], key: str) -> list[dict]:
    for row in rows:
        if row.get("mean") is None:
            row[key] = "—"
        else:
            row[key] = f"{row['mean']:.4f} ± {(row['std'] or 0.0):.4f}"
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--analysis", type=Path, default=PROJECT_ROOT / "results" / "analysis"
    )
    parser.add_argument("--output-dir", type=Path, default=PROJECT_ROOT / "reports" / "tables")
    args = parser.parse_args(argv)

    analysis = args.analysis
    summary = load_json(analysis / "summary.json")
    output = args.output_dir
    output.mkdir(parents=True, exist_ok=True)

    for metric in METRICS:
        block = summary["metrics"][metric]
        rows = mean_std([dict(row) for row in block["aggregates"]], "mean_sd")
        write(
            output / f"results_{metric}.md",
            f"{metric} per model and condition (mean ± SD over splits)",
            markdown_table(
                rows,
                [
                    ("dataset", "dataset"),
                    ("mode", "condition"),
                    ("model", "model"),
                    ("mean_sd", "mean ± SD"),
                    ("n_completed", "n completed"),
                ],
            ),
        )
        write(
            output / f"structural_delta_{metric}.md",
            f"Structural Delta ({metric} − MLP)",
            markdown_table(
                block["structural_delta"],
                [
                    ("dataset", "dataset"),
                    ("mode", "condition"),
                    ("model", "model"),
                    ("mean_delta", "mean Δ"),
                    ("std_delta", "SD Δ"),
                    ("n_pairs", "pairs"),
                ],
            ),
        )
        write(
            output / f"paired_tests_{metric}.md",
            f"Paired comparisons of {metric} against MLP (Holm corrected)",
            markdown_table(
                [
                    {
                        **row,
                        "ci": f"[{row['ci95_low']:+.4f}, {row['ci95_high']:+.4f}]",
                        "significance": "significant" if row["significant_holm_0.05"] else "not significant",
                    }
                    for row in block["paired_comparisons"]
                ],
                [
                    ("dataset", "dataset"),
                    ("mode", "condition"),
                    ("comparison", "comparison"),
                    ("n_pairs", "pairs"),
                    ("mean_difference", "mean Δ"),
                    ("std_difference", "SD Δ"),
                    ("ci", "95% CI"),
                    ("t_statistic", "t"),
                    ("p_value_ttest", "p (raw)"),
                    ("p_value_holm", "p (Holm)"),
                    ("p_value_wilcoxon", "p (Wilcoxon)"),
                    ("cohen_dz", "d_z"),
                    ("significance", "verdict"),
                ],
            ),
        )
        write(
            output / f"raw_vs_filtered_{metric}.md",
            f"Raw versus filtered {metric} (descriptive)",
            markdown_table(
                block["raw_vs_filtered"],
                [
                    ("dataset", "dataset"),
                    ("model", "model"),
                    ("mean_raw", "raw"),
                    ("mean_filtered", "filtered"),
                    ("difference_filtered_minus_raw", "Δ (filtered − raw)"),
                    ("n_raw", "n raw"),
                    ("n_filtered", "n filtered"),
                ],
            ),
        )

    write(
        output / "run_characteristics.md",
        "Parameters, epochs and timings per model and condition",
        markdown_table(
            summary["run_characteristics"],
            [
                ("dataset", "dataset"),
                ("mode", "condition"),
                ("model", "model"),
                ("trainable_parameters", "parameters"),
                ("mean_epochs_trained", "mean epochs"),
                ("mean_best_epoch", "mean best epoch"),
                ("mean_training_time_seconds", "mean train s"),
                ("mean_evaluation_time_seconds", "mean eval s"),
            ],
            float_digits=2,
        ),
    )

    ablations = summary.get("ablations", {})
    if ablations.get("variants"):
        for metric in METRICS:
            aggregates = mean_std(
                [dict(row) for row in ablations["aggregates"][metric]], "mean_sd"
            )
            write(
                output / f"ablation_results_{metric}.md",
                f"H2GCN ablations, {metric} (mean ± SD over ten splits)",
                markdown_table(
                    aggregates,
                    [
                        ("dataset", "dataset"),
                        ("mode", "condition"),
                        ("variant", "variant"),
                        ("mean_sd", "mean ± SD"),
                        ("n_completed", "n completed"),
                    ],
                ),
            )
            rows = ablations["paired"].get(metric, [])
            write(
                output / f"ablation_paired_{metric}.md",
                f"H2GCN ablations versus full H2GCN, {metric} (paired, Holm corrected)",
                markdown_table(
                    [
                        {
                            **row,
                            "ci": f"[{row['ci95_low']:+.4f}, {row['ci95_high']:+.4f}]",
                            "significance": (
                                "significant"
                                if row["significant_holm_0.05"]
                                else "not significant"
                            ),
                        }
                        for row in rows
                    ],
                    [
                        ("dataset", "dataset"),
                        ("mode", "condition"),
                        ("comparison", "variant"),
                        ("n_pairs", "pairs"),
                        ("mean_difference", "mean Δ"),
                        ("std_difference", "SD Δ"),
                        ("ci", "95% CI"),
                        ("t_statistic", "t"),
                        ("p_value_ttest", "p (raw)"),
                        ("p_value_holm", "p (Holm)"),
                        ("p_value_wilcoxon", "p (Wilcoxon)"),
                        ("cohen_dz", "d_z"),
                        ("significance", "verdict"),
                    ],
                ),
            )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
